    private static let yearsSince2016 = Array(2016...2024)
    private static let yearsSince2014 = Array(2014...2024)

    private static func parseWage(_ raw: String, years: [Int]) -> [String: [Int: Decimal]] {
        var table: [String: [Int: Decimal]] = [:]
        for line in raw.split(separator: "\n") {
            let f = line.split(separator: " ").map(String.init)
            guard let head = f.first else { continue }
            var byYear: [Int: Decimal] = [:]
            for (i, year) in years.enumerated() where i + 1 < f.count {
                let v = f[i + 1]
                if v == "—" || v == "-" { continue }
                if let d = Decimal(string: v) { byYear[year] = d }
            }
            table[normalizeProvince(head)] = byYear
        }
        return table
    }

    static let wageNonPrivate = parseWage(wageRawNonPrivate, years: yearsSince2016)
    static let wageFull = parseWage(wageRawFull, years: yearsSince2014)
    static let wagePrivate = parseWage(wageRawPrivate, years: yearsSince2016)

    /// 省名归一化：去掉一次末尾行政区后缀（北京市→北京；内蒙古自治区→内蒙古；广西壮族自治区→广西）。
    static func normalizeProvince(_ name: String) -> String {
        let suffixes = ["维吾尔自治区", "回族自治区", "壮族自治区", "特别行政区", "自治区", "自治州", "省", "市"]
        let s = name.trimmingCharacters(in: .whitespaces)
        for suf in suffixes where s.hasSuffix(suf) {
            return String(s.dropLast(suf.count))
        }
        return s
    }

    /// 某省某年某口径职工平均工资（私营/非私营=年薪；全口径=月薪）。缺则 nil。
    public func provinceWage(province: String, baseYear: Int, caliber: WageCaliber) -> Decimal? {
        let table: [String: [Int: Decimal]]
        switch caliber {
        case .privateUnit:    table = Self.wagePrivate
        case .fullUnit:       table = Self.wageFull
        case .nonPrivateUnit: table = Self.wageNonPrivate
        }
        return table[Self.normalizeProvince(province)]?[baseYear]
    }

    /// 丧葬费 = 上一年度职工月平均工资 × 6（全口径表本身是月薪；私营/非私营年薪 ÷12 得月薪）。
    public func funeralFee(province: String, baseYear: Int, caliber: WageCaliber = .privateUnit) throws -> Decimal {
        guard let wage = provinceWage(province: province, baseYear: baseYear, caliber: caliber) else {
            throw PersonalInjuryError.missingWageData
        }
        let monthly = caliber == .fullUnit ? wage : wage / 12
        return Self.round2(monthly * 6)
    }
